  let currentLang = 'es';

  function t(key) {
    return (DICTS[currentLang] && DICTS[currentLang][key]) || (DICTS.es[key] || key);
  }

  function applyI18n(lang) {
    currentLang = DICTS[lang] ? lang : 'es';
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const value = t(el.getAttribute('data-i18n-title'));
      el.title = value;
      el.setAttribute('aria-label', value);
    });
  }

  window.FireGuardI18n = { applyI18n, t, get currentLang() { return currentLang; } };
